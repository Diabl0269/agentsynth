// FilterResonanceFitTests.cpp
//
// The Filter's Resonance knob against a reference synth's 24 dB ladder low-pass, rendered with the same C2 saw at a
// 1 kHz cutoff. The reference numbers were measured through the reference synth's plug-in (octave-band power of the
// held note, Welch, 16384 points) and are pinned here as plain numbers: the bands as dB below the total power, and the
// resonant peak as the 800-1250 Hz band over the 700-800 Hz band. Passing mark: every band and peak within 1.5 dB.

#include "Modules/FilterModule.h"
#include <cmath>
#include <gtest/gtest.h>
#include <vector>

namespace {

constexpr int kFftOrder = 16;
constexpr int kFftSize = 1 << kFftOrder;
constexpr double kC2 = 65.4064;

void setParam(FilterModule& filter, const char* id, float value) {
    for (auto* p : filter.getParameters())
        if (auto* ranged = dynamic_cast<juce::RangedAudioParameter*>(p); ranged != nullptr && ranged->paramID == id)
            ranged->setValueNotifyingHost(ranged->convertTo0to1(value));
}

// A band-limited saw as the Oscillator makes it (full-scale ramp, Gibbs ringing included), generated by adding
// harmonics up to Nyquist.
std::vector<float> additiveSaw(double sampleRate, int numSamples, double f0 = kC2) {
    std::vector<float> out((size_t)numSamples, 0.0f);
    const int harmonics = (int)(sampleRate * 0.5 / f0) - 1;
    for (int n = 1; n <= harmonics; ++n) {
        const double gain = 2.0 / juce::MathConstants<double>::pi / n * ((n % 2) != 0 ? 1.0 : -1.0);
        const double step = 2.0 * juce::MathConstants<double>::pi * n * f0 / sampleRate;
        for (int i = 0; i < numSamples; ++i)
            out[(size_t)i] += (float)(gain * std::sin(step * i));
    }
    return out;
}

// The last kFftSize samples of the saw through the Filter in mono, after a second of settling.
std::vector<float> renderThroughFilter(double sampleRate, float cutoff, float resonance, int type = 0,
                                       double f0 = kC2) {
    auto filter = std::make_unique<FilterModule>(); // heap: the 16 ladders are too big for a Windows test stack
    setParam(*filter, "cutoff", cutoff);
    setParam(*filter, "resonance", resonance);
    setParam(*filter, "filterType", (float)type);
    filter->prepareToPlay(sampleRate, 512);
    const int lead = (int)sampleRate;
    const auto saw = additiveSaw(sampleRate, lead + kFftSize, f0);
    std::vector<float> out(saw.size());
    juce::MidiBuffer midi;
    for (size_t pos = 0; pos < saw.size(); pos += 512) {
        const int n = (int)std::min<size_t>(512, saw.size() - pos);
        juce::AudioBuffer<float> block(FilterModule::kNumChannels, 512);
        block.clear();
        std::copy(saw.begin() + (long)pos, saw.begin() + (long)pos + n, block.getWritePointer(0));
        filter->processBlock(block, midi);
        std::copy(block.getReadPointer(0), block.getReadPointer(0) + n, out.begin() + (long)pos);
    }
    return {out.end() - kFftSize, out.end()};
}

double bandPowerDb(const std::vector<float>& x, double sampleRate, double lo, double hi) {
    juce::dsp::FFT fft(kFftOrder);
    std::vector<float> buf(2 * kFftSize, 0.0f);
    for (int i = 0; i < kFftSize; ++i)
        buf[(size_t)i] = x[(size_t)i] * (0.5f - 0.5f * std::cos(2.0f * juce::MathConstants<float>::pi * i / kFftSize));
    fft.performRealOnlyForwardTransform(buf.data(), true);
    double sum = 0.0;
    for (int k = 1; k < kFftSize / 2; ++k) {
        const double f = k * sampleRate / kFftSize;
        if (f >= lo && f < hi)
            sum += (double)buf[(size_t)2 * k] * buf[(size_t)2 * k] +
                   (double)buf[(size_t)2 * k + 1] * buf[(size_t)2 * k + 1];
    }
    return 10.0 * std::log10(sum + 1e-30);
}

// Gain in dB of each harmonic of a saw at `f0`, with the saw's own 1/n fall removed, as (Hz, dB) points.
void addHarmonicGains(const std::vector<float>& x, double sampleRate, double f0,
                      std::vector<std::pair<double, double>>& out) {
    juce::dsp::FFT fft(kFftOrder);
    std::vector<float> buf(2 * kFftSize, 0.0f);
    for (int i = 0; i < kFftSize; ++i)
        buf[(size_t)i] = x[(size_t)i] * (0.5f - 0.5f * std::cos(2.0f * juce::MathConstants<float>::pi * i / kFftSize));
    fft.performRealOnlyForwardTransform(buf.data(), true);
    const double binHz = sampleRate / kFftSize;
    for (int n = 1; n * f0 < 20000.0; ++n) {
        double top = 0.0;
        for (int k = (int)((n * f0 - f0 / 4) / binHz); k <= (int)((n * f0 + f0 / 4) / binHz); ++k)
            top = std::max(top, std::hypot((double)buf[(size_t)2 * k], (double)buf[(size_t)2 * k + 1]));
        out.emplace_back(n * f0, 20.0 * std::log10(top * n + 1e-30));
    }
}

struct Peak {
    double hz;
    double heightDb; // over the median gain between 150 and 400 Hz
};

// The resonant peak of a saw at sixteen pitches (C2 up to D#3) so the harmonics together sample the spectrum finely:
// the strongest point from 0.5 to 1.4 x cutoff, placed by a parabola through every point within 3 dB of it.
Peak peakOfSawSweep(double sampleRate, float cutoff, float resonance) {
    std::vector<std::pair<double, double>> pts;
    for (int i = 0; i < 16; ++i) {
        const double f0 = 440.0 * std::pow(2.0, (36 + i - 69) / 12.0);
        addHarmonicGains(renderThroughFilter(sampleRate, cutoff, resonance, 0, f0), sampleRate, f0, pts);
    }
    std::vector<double> pass;
    std::pair<double, double> top{0.0, -1e9};
    for (const auto& p : pts) {
        if (p.first > 150.0 && p.first < 400.0)
            pass.push_back(p.second);
        if (p.first > 0.5 * cutoff && p.first < 1.4 * cutoff && p.second > top.second)
            top = p;
    }
    std::sort(pass.begin(), pass.end());
    // Least squares of dB on log2(Hz / top) over the points within 3 dB of the top.
    double s0 = 0, s1 = 0, s2 = 0, s3 = 0, s4 = 0, t0 = 0, t1 = 0, t2 = 0;
    for (const auto& p : pts)
        if (p.first > 0.5 * cutoff && p.first < 1.4 * cutoff && p.second > top.second - 3.0) {
            const double x = std::log2(p.first / top.first);
            s0 += 1;
            s1 += x;
            s2 += x * x;
            s3 += x * x * x;
            s4 += x * x * x * x;
            t0 += p.second;
            t1 += x * p.second;
            t2 += x * x * p.second;
        }
    // Normal equations [s0 s1 s2; s1 s2 s3; s2 s3 s4] u = [t0 t1 t2] for g = u0 + u1 x + u2 x^2, by Cramer's rule.
    const auto det3 = [](double a, double b, double c, double d, double e, double f, double g, double h, double i) {
        return a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g);
    };
    const double det = det3(s0, s1, s2, s1, s2, s3, s2, s3, s4);
    const double u0 = det3(t0, s1, s2, t1, s2, s3, t2, s3, s4) / det;
    const double u1 = det3(s0, t0, s2, s1, t1, s3, s2, t2, s4) / det;
    const double u2 = det3(s0, s1, t0, s1, s2, t1, s2, s3, t2) / det;
    const double passband = pass[pass.size() / 2];
    Peak out{top.first, top.second - passband};
    if (det != 0.0 && u2 < 0.0) {
        const double xm = -u1 / (2.0 * u2);
        out.hz = top.first * std::pow(2.0, xm);
        out.heightDb = u0 + u1 * xm + u2 * xm * xm - passband;
    }
    return out;
}

struct Reference {
    float resonance;
    double bandsBelowTotalDb[5]; // 160-320, 320-640, 640-1280, 1280-2560, 2560-5120 Hz
    double peakOverBandBelowDb;  // 800-1250 Hz over 700-800 Hz
};

// Measured from the reference synth (24 dB ladder low-pass, 1 kHz, C2 saw) at knob 0, 50, 90 and 100 %.
const Reference kReference[] = {
    {0.0f, {-9.99, -13.67, -23.16, -39.36, -62.07}, -1.3},
    {0.5f, {-9.78, -9.87, -9.93, -29.51, -53.73}, 0.1},
    {0.9f, {-12.27, -12.63, -3.11, -26.90, -52.44}, 12.5},
    {1.0f, {0, 0, 0, 0, 0}, 16.0}, // bands not pinned at the end stop
};

} // namespace

// Regression test for FRO1348: the ladder saturated the Oscillator's full-scale saw, so the resonant peak at 90 %
// read +5 dB over the band below where the reference reads +12.5 dB.
TEST(FilterResonanceFit, PeakOverTheBandBelowMatchesTheReference) {
    constexpr double sr = 48000.0;
    for (const auto& ref : kReference) {
        const auto y = renderThroughFilter(sr, 1000.0f, ref.resonance);
        const double peak = bandPowerDb(y, sr, 800.0, 1250.0) - bandPowerDb(y, sr, 700.0, 800.0);
        EXPECT_NEAR(peak, ref.peakOverBandBelowDb, 1.5) << "resonance " << ref.resonance;
    }
}

// Regression test for FRO1348: at 0 % the ladder kept a floor of feedback (+2.4 dB at 640-1280 Hz against the
// reference) and at 90 % the peak was squashed (-4 dB there).
TEST(FilterResonanceFit, OctaveBandsMatchTheReferenceOnceLevelsAreMatched) {
    constexpr double sr = 48000.0;
    constexpr double edges[] = {160.0, 320.0, 640.0, 1280.0, 2560.0, 5120.0};
    for (const auto& ref : kReference) {
        if (ref.resonance > 0.95f)
            continue; // 100 % is pinned by the peak test; the 4 kHz peak limit differs at the knob's end stop
        const auto y = renderThroughFilter(sr, 1000.0f, ref.resonance);
        const double total = bandPowerDb(y, sr, 20.0, 20000.0);
        for (int b = 0; b < 5; ++b)
            EXPECT_NEAR(bandPowerDb(y, sr, edges[b], edges[b + 1]) - total, ref.bandsBelowTotalDb[b], 1.5)
                << "resonance " << ref.resonance << " band " << edges[b] << "-" << edges[b + 1];
    }
}

// Regression test for FRO1367: the peak fell away at high cutoffs (knob 70 % at 8 kHz read +2.2 dB where the reference
// reads +6.0, knob 90 % +10.8 against +12.8). Peaks are the cutoff band (0.8-1.25x) over the band below (0.7-0.8x),
// measured from the reference at 48 kHz with the same C2 saw.
TEST(FilterResonanceFit, PeakHoldsItsHeightAtHighCutoffs) {
    constexpr double sr = 48000.0;
    const struct {
        float cutoff;
        float resonance;
        double peakDb;
    } measured[] = {{4000.0f, 0.7f, 6.3},  {4000.0f, 0.9f, 13.2}, {6000.0f, 0.7f, 5.9},
                    {6000.0f, 0.9f, 12.8}, {8000.0f, 0.7f, 6.0},  {8000.0f, 0.9f, 12.8}};
    for (const auto& m : measured) {
        const auto y = renderThroughFilter(sr, m.cutoff, m.resonance);
        const double peak =
            bandPowerDb(y, sr, 0.8 * m.cutoff, 1.25 * m.cutoff) - bandPowerDb(y, sr, 0.7 * m.cutoff, 0.8 * m.cutoff);
        EXPECT_NEAR(peak, m.peakDb, 1.5) << "cutoff " << m.cutoff << " resonance " << m.resonance;
    }
}

// Regression test for FRO1367: the one-sample feedback delay pulled the peak below the cutoff as the cutoff neared the
// sample rate (knob 90 % at 8 kHz peaked at 7124 Hz where the reference peaks at 7743, 12 kHz at 9716 against 11649).
// Peaks measured from the reference at 48 kHz with the same sixteen-pitch saw sweep; heights over the passband.
TEST(FilterResonanceFit, PeakSitsWhereTheReferencePutsIt) {
    constexpr double sr = 48000.0;
    const struct {
        float cutoff;
        float resonance;
        double peakHz;
        double heightDb;
    } measured[] = {{6000.0f, 0.9f, 5806.0, 22.5}, {8000.0f, 0.7f, 7164.0, 12.4},  {8000.0f, 0.9f, 7743.0, 22.1},
                    {8000.0f, 1.0f, 7960.0, 37.3}, {10000.0f, 0.9f, 9679.0, 22.0}, {12000.0f, 0.9f, 11649.0, 21.8}};
    for (const auto& m : measured) {
        const auto peak = peakOfSawSweep(sr, m.cutoff, m.resonance);
        EXPECT_NEAR(1200.0 * std::log2(peak.hz / m.peakHz), 0.0, 60.0)
            << "cutoff " << m.cutoff << " resonance " << m.resonance << " peak at " << peak.hz << " Hz";
        EXPECT_NEAR(peak.heightDb, m.heightDb, 2.5) << "cutoff " << m.cutoff << " resonance " << m.resonance;
    }
}

// The knob end stop: every ladder type, three sample rates, no NaN, bounded, and silent again once the input stops
// (the ladder rings but never sustains on its own).
TEST(FilterResonanceFit, TopOfTheKnobIsStableAndDoesNotSelfSustain) {
    for (const double sr : {44100.0, 48000.0, 96000.0})
        for (int type = 0; type <= 5; ++type)
            for (const float cutoff : {200.0f, 1000.0f, 8000.0f, 18000.0f}) {
                auto filter = std::make_unique<FilterModule>();
                setParam(*filter, "cutoff", cutoff);
                setParam(*filter, "resonance", 1.0f);
                setParam(*filter, "filterType", (float)type);
                filter->prepareToPlay(sr, 512);
                juce::Random rng(7);
                juce::MidiBuffer midi;
                const int burst = (int)(sr * 0.25), total = (int)(sr * 4.0);
                float peak = 0.0f, tail = 0.0f;
                for (int pos = 0; pos < total; pos += 512) {
                    juce::AudioBuffer<float> block(FilterModule::kNumChannels, 512);
                    block.clear();
                    for (int i = 0; i < 512; ++i)
                        if (pos + i < burst)
                            block.setSample(0, i, rng.nextFloat() * 2.0f - 1.0f);
                    filter->processBlock(block, midi);
                    for (int i = 0; i < 512; ++i) {
                        const float v = block.getSample(0, i);
                        ASSERT_TRUE(std::isfinite(v)) << "type " << type << " sr " << sr << " cutoff " << cutoff;
                        peak = std::max(peak, std::abs(v));
                        if (pos + i > total - (int)(sr * 0.5))
                            tail = std::max(tail, std::abs(v));
                    }
                }
                EXPECT_LT(peak, 200.0f) << "type " << type << " sr " << sr << " cutoff " << cutoff;
                EXPECT_LT(tail, 1.0e-3f) << "type " << type << " sr " << sr << " cutoff " << cutoff;
            }
}
